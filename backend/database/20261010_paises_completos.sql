SELECT n.nombre
FROM paises_nuevos n
WHERE NOT EXISTS (
    SELECT 1 FROM pais p WHERE p.nombre COLLATE utf8mb4_unicode_ci = n.nombre COLLATE utf8mb4_unicode_ci
);

